const SLUG_ALIASES: Record<string, string> = {
  "pathology": "histopathology",
  "pharmacy": "pharmacology",
  "biomedical-sciences": "chemical-pathology",
  "nursing-sciences": "clinical-medicine",
  "public-speaking-and-presentation-skills": "public-speaking",
  "leadership-and-management": "leadership",
  "coding-and-software-development": "coding-and-health-informatics",
  "entrepreneurship": "healthcare-entrepreneurship",
  "antimicrobial-resistance": "antimicrobial-stewardship",
}

export function getAllCourses(): Course[] {
  return COURSES_CATALOG
}

export function getCoursesByCategory(category: CourseCategory): Course[] {
  return COURSES_CATALOG.filter((c) => c.category === category)
}

export function getCourseBySlug(slug: string): Course | undefined {
  const resolvedSlug = SLUG_ALIASES[slug] || slug
  return COURSES_CATALOG.find((c) => c.slug === resolvedSlug || c.id === resolvedSlug)
}
